ALTER SESSION SET CONTAINER = FREEPDB1;

-- 1. Tablespaces dedicados para datos e índices
CREATE TABLESPACE TS_FINTECH_DATA
    DATAFILE 'ts_fintech_data_01.dbf' SIZE 100M AUTOEXTEND ON NEXT 50M MAXSIZE 2G
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

CREATE TABLESPACE TS_FINTECH_IDX
    DATAFILE 'ts_fintech_idx_01.dbf' SIZE 50M AUTOEXTEND ON NEXT 25M MAXSIZE 1G
    EXTENT MANAGEMENT LOCAL AUTOALLOCATE
    SEGMENT SPACE MANAGEMENT AUTO;

-- 2. Usuario de Dominio
CREATE USER FINTECH_USER IDENTIFIED BY "FintechMaster2026!"
    DEFAULT TABLESPACE TS_FINTECH_DATA
    TEMPORARY TABLESPACE TEMP
    QUOTA UNLIMITED ON TS_FINTECH_DATA
    QUOTA UNLIMITED ON TS_FINTECH_IDX;

-- 3. Privilegios de Sistema y Telemetría
GRANT CONNECT, RESOURCE, CREATE VIEW, CREATE PROCEDURE, CREATE SEQUENCE, CREATE JOB TO FINTECH_USER;
GRANT SELECT ON V_$SESSION TO FINTECH_USER;
GRANT SELECT ON V_$SQL TO FINTECH_USER;
GRANT SELECT ON V_$SQL_PLAN TO FINTECH_USER;
GRANT SELECT ON V_$SQL_PLAN_STATISTICS_ALL TO FINTECH_USER;

EXIT;
